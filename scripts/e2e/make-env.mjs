#!/usr/bin/env node
// Writes the env file for an ISOLATED e2e stack: `.env.example` with the e2e port block in place of the dev block, and every
// URL that points at a port moved with it. Run it once per checkout; the stack and the e2e run both read the result.
//
//   node scripts/e2e/make-env.mjs .env.e2e
//
// The e2e block sits beside the dev block (see the port table in README → "Local development"), so a dev stack and an e2e
// stack can run at the same time on one machine. The compose project name is set here too, so `docker compose --env-file`
// and the containers agree on it. The output is git-ignored.
import { readFileSync, writeFileSync } from 'node:fs';

const [out = '.env.e2e'] = process.argv.slice(2);
const DEV_TO_E2E = {
  5420: 5460, // Postgres
  6320: 6360, // Valkey
  4620: 4660, // LocalStack (S3, Secrets)
  4420: 4460, // OTel OTLP
  8420: 8460, // OTel metrics
  1120: 1160, // Mailpit SMTP
  8120: 8160, // Mailpit UI
  5175: 5195, // web dev server
  3010: 3020, // API
};

let text = readFileSync('.env.example', 'utf8');
for (const [dev, e2e] of Object.entries(DEV_TO_E2E)) {
  text = text.replace(new RegExp(`(?<![0-9])${dev}(?![0-9])`, 'g'), String(e2e));
}
text = text.replace(/^# COMPOSE_PROJECT_NAME=.*$/m, '');
const header = `# Generated by scripts/e2e/make-env.mjs from .env.example: the e2e port block, not the dev one. Do not edit by hand.\nCOMPOSE_PROJECT_NAME=${process.env.COMPOSE_PROJECT_NAME ?? 'rova-e2e'}\n`;
writeFileSync(out, header + text);
console.log(`wrote ${out} (e2e ports: ${Object.values(DEV_TO_E2E).join(', ')})`);
